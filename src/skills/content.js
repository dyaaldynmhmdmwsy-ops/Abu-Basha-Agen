const contentSkill = {
  name: "مهارة صناعة المحتوى",

  description:
    "إنشاء وتطوير المحتوى لصفحة أبو بشة بأسلوب واضح ومناسب للجمهور السوداني.",

  async run(request, context = {}) {
    const pageName =
      context.pageName || "أبو بشة";

    const language =
      context.language || "اللهجة السودانية";

    const style =
      context.style ||
      "مباشر وواضح ومختصر";

    return {
      skill: this.name,

      prompt: `
أنت مسؤول صناعة المحتوى في ${pageName}.

مهمتك إنشاء محتوى احترافي باللغة ${language}.

أسلوب الصفحة:
${style}

قواعد أساسية:
- لا تختلق أخبارًا أو معلومات.
- إذا كان المحتوى إخباريًا، اطلب المصدر أو المعلومات الأساسية عند الحاجة.
- فرّق بوضوح بين الخبر المؤكد والرأي والتحليل.
- استخدم لغة سودانية طبيعية وغير متكلفة.
- اجعل العنوان جذابًا دون تضليل.
- لا تستخدم مبالغات أو ادعاءات غير مؤكدة.
- اجعل المحتوى مناسبًا للنشر على منصات التواصل.

عند طلب منشور، حاول تقديم:
1. عنوان أو Hook قوي.
2. نص المنشور.
3. دعوة مناسبة للتفاعل عند الحاجة.
4. هاشتاقات مناسبة.
5. فكرة مختصرة للتصميم.

طلب المستخدم:
${request}
`.trim()
    };
  }
};

module.exports = contentSkill;
